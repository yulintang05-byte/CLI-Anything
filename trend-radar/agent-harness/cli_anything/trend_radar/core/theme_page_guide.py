class ThemePageGuide:
    """Theme page knowledge base, niche research, and conversion guides."""

    def get_guide(self, topic: str = "overview") -> dict:
        """Get theme page guide content.

        topic: 'overview' | 'setup' | 'content' | 'growth' | 'monetize' | 'all'
        Returns dict of section_name → content (list or str).
        """
        if topic == "all":
            result: dict = {}
            for t in ["overview", "setup", "content", "growth", "monetize"]:
                result.update(THEME_GUIDE.get(t, {}))
            return result
        return THEME_GUIDE.get(topic, THEME_GUIDE["overview"])

    def find_niches(self, category: str = "all", platform: str = "instagram") -> list[dict]:
        """Find profitable theme page niches sorted by growth potential.

        Returns list of niche dicts with category, competition, monetization,
        growth_potential, and examples fields.
        """
        if category == "all":
            all_niches = []
            for cat, niches in NICHES.items():
                if cat != "all":
                    for n in niches:
                        all_niches.append({**n, "category": cat})
            _order = {"very high": 0, "high": 1, "medium": 2, "low": 3}
            return sorted(all_niches, key=lambda x: _order.get(x.get("growth_potential", "medium"), 2))
        return [
            {**n, "category": category}
            for n in NICHES.get(category.lower(), [])
        ]

    def get_conversion_tips(
        self,
        from_type: str = "personal",
        to_type: str = "theme",
        platform: str = "instagram",
    ) -> dict:
        """Get a phased account conversion guide.

        Returns dict of phase_name → list of steps.
        """
        key = (from_type, to_type)
        return CONVERSION_GUIDES.get(key, DEFAULT_CONVERSION)

