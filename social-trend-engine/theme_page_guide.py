from __future__ import annotations


THEME_PAGE_GUIDE = """
╔══════════════════════════════════════════════════════════════════╗
║          THEME PAGE MASTERY — COMPLETE GUIDE & ROADMAP          ║
╚══════════════════════════════════════════════════════════════════╝

WHAT IS A THEME PAGE?
─────────────────────
A theme page (aka aggregation/repost page) is an account built around
a specific topic or aesthetic — not a personal brand. You curate and
repost the BEST viral content in that niche, building a large following
without showing your face or creating original content.

Examples: @9gag, @daquan, @gymtok, @motivationalvideos, dog meme pages,
luxury lifestyle pages, nature/travel compilations.


PHASE 1 — NICHE SELECTION (Week 1)
────────────────────────────────────
Pick a niche with ALL 3 of these traits:
  [1] PASSION NICHE: people obsess over it (fitness, dogs, cars, food)
  [2] VISUAL NICHE: content is watchable without context (comedy, nature)
  [3] REPLENISHABLE: new viral content is made daily (not one-time events)

BEST THEME PAGE NICHES (ranked by monetization potential):
  Tier A: Fitness / Gym Motivation, Finance / Hustle, Luxury/Wealth
  Tier B: Comedy / Memes, Food, Dogs/Animals, Cars
  Tier C: Nature, Travel, Art/Aesthetics, Motivation

AVOID:
  - Niches you hate (you'll quit at month 1)
  - Saturated niches without a sub-niche angle
  - News/politics (high ban risk, volatile algorithm)


PHASE 2 — ACCOUNT SETUP (Week 1)
──────────────────────────────────
Profile blueprint:
  Username  : @[NicheKeyword][Word] (e.g., @GymNation, @HustleDrive)
  Bio       : [What you post] • [Post frequency] • [CTA/DM for promos]
  Link      : Linktree → affiliate link + other socials
  Logo      : Clean, high-contrast (use Canva free)
  Aesthetic : Pick ONE color palette and stick to it

Set up on:
  ① TikTok     (fastest growth, lowest barrier)
  ② Instagram  (Reels = free reach + link in bio monetization)
  ③ YouTube    (Shorts for theme pages = passive long-term income)


PHASE 3 — CONTENT SOURCING & POSTING (Weeks 2-4)
──────────────────────────────────────────────────
WHERE TO FIND VIRAL CONTENT:

  YouTube:
    • Subscribe to top 20 creators in your niche
    • "Sort by: Popular" on any channel
    • YouTube trending page (category-specific)

  TikTok:
    • Search your niche hashtag → sort by "Most Liked" (7 days)
    • Check "For You" page after training your algorithm
    • Use this tool: python main.py scrape --platform tiktok --hashtag [niche]

  Reddit:
    • r/[niche] → sort by Hot/Top
    • Unironic goldmine for original content ideas

  Twitter/X:
    • Search [niche] + filter:videos + min_faves:1000

CONTENT POSTING RULES:
  • Always credit original creator in caption or comments
  • Download with yt-dlp (no watermarks: --no-playlist -f best)
  • Post 3-5x per day on TikTok during growth phase
  • Add YOUR hook text on top of reposts (adds value, reduces strikes)
  • Do NOT just repost — add context, commentary, or compilation value


PHASE 4 — GROWTH ACCELERATION (Months 1-3)
─────────────────────────────────────────────
CROSS-PROMOTION STRATEGY:
  Post same content to: TikTok → Instagram Reels → YouTube Shorts
  One piece of content = 3 chances to go viral.

ENGAGEMENT FARMING (safe & ethical):
  • Comment on viral posts in your niche: adds visibility
  • Reply to every comment on your posts (first 48h)
  • DM collaborations with pages at same follower level

ALGORITHM TRIGGERS:
  TikTok: Saves + Shares are weighted most. Create "save-worthy" content.
  Instagram Reels: Shares to Stories = #1 growth signal
  YouTube Shorts: Watch-through rate → shares → subscriber conversion

GROWTH MILESTONES:
  0–1K    : Post-and-pray phase. Test 10 content styles, find winner.
  1K–10K  : Double down on top 3 performing video types. Post 5x/day.
  10K–50K : Start monetizing. DMs open for paid promos.
  50K–100K: Negotiating paid brand deals. Scale to 2nd page.
  100K+   : Full brand deal income. Launch paid community / products.


PHASE 5 — MONETIZATION (Month 2 onward)
─────────────────────────────────────────
INCOME STREAMS (ranked by ease + income):

  ① SHOUTOUTS / PAID PROMOS (10K+ followers)
       Charge: $10–50 per 10K followers per post
       Find clients: DM brands in niche, reply to creator fund ads

  ② AFFILIATE MARKETING (any size)
       Amazon Associates, ShareASale, Impact.com
       Post review/compilation → link in bio → earn 4-8% commission
       Example: fitness page → GNC, MyProtein, gym equipment

  ③ DIGITAL PRODUCTS (50K+)
       Preset packs (photography), workout plans, recipe PDFs
       High margin: create once, sell forever

  ④ YOUTUBE AD REVENUE (via Shorts/Compilations)
       Compilation channels can hit $2–10 CPM
       Need: 1K subs + 4K watch hours (or 10M Shorts views/90 days)

  ⑤ NEWSLETTER / EMAIL LIST
       Convert followers → subscribers (more algorithm-proof)
       Monetize via affiliate + product recommendations


PHASE 6 — SCALING TO MULTIPLE PAGES
──────────────────────────────────────
Once first page hits 50K:
  1. Document your exact posting workflow (time/hashtags/sources)
  2. Start Page #2 in adjacent niche (same audience, different content)
  3. Cross-promote between pages (free follower transfer)
  4. Hire a VA ($5-15/hr) to handle posting schedule
  5. You focus: sourcing 10 videos/day + strategy

SYSTEM (repeatable daily workflow):
  Morning  : Scrape trending (this tool) → download top 10 clips
  Afternoon: Edit/caption → schedule posts (Later, Buffer, TikTok scheduler)
  Evening  : Engage (30 min) → check analytics → adjust tomorrow's plan


CONVERSION TACTICS (turn followers → customers)
─────────────────────────────────────────────────
  LINK IN BIO FUNNEL:
    Post → Profile → Bio CTA → Linktree → Product/Affiliate

  STORY/CAPTION CTA:
    "Save this for later"  → increases save rate → more reach
    "Tag someone who needs this" → shares → exponential reach
    "DM me [keyword] for the guide" → builds DM relationship

  SOFT SELL (non-annoying):
    80% value content : 20% promo content ratio
    Integrate product naturally into existing content style
    Testimonials and social proof in captions

  EMAIL CAPTURE:
    "Get my FREE [resource] — link in bio"
    ConvertKit or Beehiiv (free plans available)
    Send weekly trend roundup → build trust → promote products


TOOLS RECOMMENDED
──────────────────
  Content Download : yt-dlp (this project)
  Scheduling       : Later.com, Buffer, TikTok built-in scheduler
  Editing          : CapCut (free, trend templates), Canva
  Analytics        : TikTok Analytics, YouTube Studio, Iconosquare
  Hashtag Research : This tool (python main.py hashtags --niche [x])
  Trend Discovery  : This tool (python main.py scrape --platform youtube)
  Bio Links        : Linktree, Beacons.ai (free)
  Email            : Beehiiv (free to 2,500 subscribers)


LEGAL & ETHICAL NOTES
──────────────────────
  • Always credit original creators
  • Use Creative Commons content when possible
  • Transformative use (commentary, compilation, education) is safer
  • Read each platform's repost/repurpose policies before scaling
  • Register a business entity once earning >$1K/month (liability)

"""


