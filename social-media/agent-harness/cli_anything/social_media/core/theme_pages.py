def get_playbook(section: Optional[str] = None) -> dict:
    if section is None:
        return THEME_PAGE_PLAYBOOK
    if section in THEME_PAGE_PLAYBOOK:
        return {section: THEME_PAGE_PLAYBOOK[section]}
    return {
        "error": f"Section '{section}' not found",
        "available_sections": list(THEME_PAGE_PLAYBOOK.keys()),
    }


def get_stage(stage_num: int) -> dict:
    stages = THEME_PAGE_PLAYBOOK["stages"]
    for s in stages:
        if s["stage"] == stage_num:
            return s
    return {
        "error": f"Stage {stage_num} not found",
        "available_stages": [s["stage"] for s in stages],
    }


